BEGIN;

ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS forma_pagamento varchar(255);
ALTER TABLE agendamento ADD COLUMN IF NOT EXISTS finalizado_em timestamp(6);

CREATE TABLE IF NOT EXISTS comissao_barbeiro (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id bigint REFERENCES agendamento(id),
    barbeiro_id bigint REFERENCES barbeiro(id),
    tipo varchar(255),
    valor_base numeric(38,2),
    percentual_aplicado numeric(38,2),
    valor_comissao numeric(38,2),
    criado_em timestamp(6)
);

-- Rejeita duplicatas preexistentes em vez de apagar comissoes.
CREATE UNIQUE INDEX IF NOT EXISTS ux_comissao_barbeiro_agendamento
    ON comissao_barbeiro (agendamento_id);

