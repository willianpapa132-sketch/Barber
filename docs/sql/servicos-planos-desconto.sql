-- Aplicar depois de finalizacao-agendamento.sql, antes de iniciar a nova versao.
BEGIN;

CREATE TABLE IF NOT EXISTS servicos_planos_desconto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_mensal_id bigint NOT NULL REFERENCES plano_mensal(id),
    porcentagem_desconto integer NOT NULL CHECK (porcentagem_desconto BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS servicos_planos_desconto_servicos (
    desconto_id bigint NOT NULL REFERENCES servicos_planos_desconto(id),
    servico_id bigint NOT NULL REFERENCES servico(id),
    PRIMARY KEY (desconto_id, servico_id)
);

CREATE TABLE IF NOT EXISTS agendamento_servicos_plano (
    agendamento_id bigint NOT NULL REFERENCES agendamento(id),
    ordem integer NOT NULL,
    servico_id bigint NOT NULL REFERENCES servico(id),
    nome varchar(255) NOT NULL,
    duracao_minutos integer NOT NULL CHECK (duracao_minutos > 0),
    incluso_no_plano boolean NOT NULL,
    preco_original numeric(12,2) NOT NULL CHECK (preco_original >= 0),
    porcentagem_desconto integer NOT NULL CHECK (porcentagem_desconto BETWEEN 0 AND 100),
    preco_liquido numeric(12,2) NOT NULL CHECK (preco_liquido >= 0),
    PRIMARY KEY (agendamento_id, ordem)
);

-- Agendamentos antigos nao sao recalculados por esta atualizacao.
-- Os novos guardam os precos, descontos e minutos aceitos pelo cliente.
COMMIT;
