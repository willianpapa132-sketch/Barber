-- Fechamento financeiro passa a pertencer a comanda; V1-V4 permanecem intactas.
alter table produto add column percentual_comissao numeric(5,2) not null default 0 check (percentual_comissao between 0 and 100);
create table comanda (
    id bigint generated by default as identity primary key,
    empresa_id uuid not null references platform_empresa(id),
    agendamento_id bigint not null unique references agendamento(id),
    barbeiro_id bigint not null references barbeiro(id),
    nome_cliente varchar(255) not null,
    fechado_em timestamp(6) not null,
    fechado_por varchar(255) not null,
    legado boolean not null default false,
    observacao varchar(500),
    tipo_desconto varchar(255) not null,
    valor_desconto_informado numeric(12,2) not null,
    subtotal numeric(12,2) not null check (subtotal>=0),
    desconto numeric(12,2) not null check (desconto>=0 and desconto<=subtotal),
    total numeric(12,2) not null check (total=subtotal-desconto),
    total_comissao numeric(12,2) not null check (total_comissao>=0),
    pontos integer not null check (pontos>=0),
    minutos integer not null check (minutos>=0)
);
create index ix_comanda_empresa_fechamento on comanda(empresa_id,fechado_em,id);
create index ix_comanda_barbeiro_fechamento on comanda(barbeiro_id,fechado_em);
create table comanda_item (
    comanda_id bigint not null references comanda(id),
    ordem integer not null,
    tipo varchar(255) not null check (tipo in ('SERVICO','PRODUTO','LEGADO')),
    servico_id bigint references servico(id),
    produto_id bigint references produto(id),
    nome varchar(255) not null,
    quantidade integer not null check (quantidade>0),
    minutos integer not null check (minutos>=0),
    pontos integer not null check (pontos>=0),
    preco_unitario numeric(12,2) not null check (preco_unitario>=0),
    subtotal numeric(12,2) not null check (subtotal>=0),
    desconto numeric(12,2) not null check (desconto>=0 and desconto<=subtotal),
    total numeric(12,2) not null check (total=subtotal-desconto),
    percentual_comissao numeric(5,2) not null check (percentual_comissao between 0 and 100),
    comissao numeric(12,2) not null check (comissao>=0),
    incluido_no_plano boolean not null,
    primary key(comanda_id,ordem),
    check ((tipo='SERVICO' and servico_id is not null and produto_id is null) or
           (tipo='PRODUTO' and produto_id is not null and servico_id is null) or
           (tipo='LEGADO' and produto_id is null and servico_id is null))
);
create index ix_comanda_item_produto on comanda_item(produto_id);
create index ix_comanda_item_servico on comanda_item(servico_id);
create table comanda_pagamento (
    comanda_id bigint not null references comanda(id),
    ordem integer not null,
    forma varchar(255) not null check (forma in ('DINHEIRO','PIX','DEBITO','CREDITO','LEGADO')),
    valor numeric(12,2) not null check (valor>0),
    primary key(comanda_id,ordem)
);
alter table comissao_barbeiro add column comanda_id bigint unique references comanda(id);
alter table comissao_plano add column comanda_id bigint unique references comanda(id);
alter table movimento_caixa add column comanda_id bigint unique references comanda(id);

-- Preserva a receita e as comissoes anteriores, sem recalcular precos nem baixar estoque.
insert into comanda(empresa_id,agendamento_id,barbeiro_id,nome_cliente,fechado_em,fechado_por,legado,
    observacao,tipo_desconto,valor_desconto_informado,subtotal,desconto,total,total_comissao,pontos,minutos)
select a.empresa_id,a.id,a.barbeiro_id,coalesce(a.nome_cliente,cl.nome,'Cliente avulso'),
    coalesce(a.finalizado_em,a.atualizado_em,a.criado_em,a.data+a.hora_finalizacao),
    'LEGADO',true,'Importado da finalizacao anterior; valores originais preservados','NENHUM',0,
    coalesce(a.preco_total,0),0,coalesce(a.preco_total,0),coalesce(cb.valor_comissao,0),coalesce(cp.pontos,0),coalesce(a.duracao_servico_minutos,0)
from agendamento a left join cliente cl on cl.id=a.cliente_id
left join comissao_barbeiro cb on cb.agendamento_id=a.id left join comissao_plano cp on cp.agendamento_id=a.id
where a.status='CONCLUIDO' and a.pagamento_recebido=true;

insert into comanda_item(comanda_id,ordem,tipo,nome,quantidade,minutos,pontos,preco_unitario,subtotal,desconto,total,percentual_comissao,comissao,incluido_no_plano)
select c.id,0,'LEGADO','Atendimento historico',1,c.minutos,c.pontos,c.total,c.total,0,c.total,
    case when c.total>0 then least(100,round(c.total_comissao*100/c.total,2)) else 0 end,c.total_comissao,false from comanda c;
insert into comanda_pagamento(comanda_id,ordem,forma,valor)
select c.id,0,case when a.forma_pagamento in ('DINHEIRO','PIX','DEBITO','CREDITO') then a.forma_pagamento else 'LEGADO' end,c.total
from comanda c join agendamento a on a.id=c.agendamento_id where c.total>0;

update comissao_barbeiro cb set comanda_id=c.id from comanda c where c.agendamento_id=cb.agendamento_id;
update comissao_plano cp set comanda_id=c.id from comanda c where c.agendamento_id=cp.agendamento_id;
update movimento_caixa m set comanda_id=c.id from comanda c where c.agendamento_id=m.agendamento_id and m.tipo='ENTRADA';
-- Registros financeiros inconsistentes precisam ser regularizados; nao inventar receita.
do $$ begin
    if exists(select 1 from comissao_barbeiro where comanda_id is null)
       or exists(select 1 from comissao_plano where comanda_id is null)
       or exists(select 1 from movimento_caixa where tipo='ENTRADA' and comanda_id is null) then
        raise exception 'Existem comissoes ou entradas sem finalizacao paga concluida. Regularize os registros legados antes de migrar comandas.';
    end if;
end $$;
