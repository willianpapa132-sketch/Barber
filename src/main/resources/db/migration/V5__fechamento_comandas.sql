-- A comanda precisa pertencer ao mesmo agendamento/barbeiro dos lancamentos.
create function barber_validar_comanda_lancamento() returns trigger language plpgsql as $$
declare a bigint; b bigint; begin
    if new.comanda_id is null then return new; end if;
    select agendamento_id,barbeiro_id into a,b from comanda where id=new.comanda_id;
    if new.agendamento_id is distinct from a then raise exception 'Comanda e agendamento divergentes' using errcode='23514'; end if;
    if TG_TABLE_NAME in ('comissao_barbeiro','comissao_plano') and (to_jsonb(new)->>'barbeiro_id')::bigint is distinct from b then
        raise exception 'Comanda e barbeiro divergentes' using errcode='23514';
    end if;
    return new;
end $$;
create trigger trg_comissao_barbeiro_comanda before insert or update on comissao_barbeiro for each row execute function barber_validar_comanda_lancamento();
create trigger trg_comissao_plano_comanda before insert or update on comissao_plano for each row execute function barber_validar_comanda_lancamento();
create trigger trg_movimento_comanda before insert or update on movimento_caixa for each row execute function barber_validar_comanda_lancamento();

-- Confere o fechamento ao fim da transacao, depois de inserir as colecoes JPA.
create function barber_conferir_totais_comanda() returns trigger language plpgsql as $$
declare cid bigint; c comanda%rowtype; itens numeric; pagamentos numeric; comissoes numeric; descontos numeric; subtotais numeric; begin
    if TG_TABLE_NAME='comanda' then cid:=new.id; else cid:=coalesce(new.comanda_id,old.comanda_id); end if;
    select * into c from comanda where id=cid;
    if not found then return null; end if;
    select coalesce(sum(total),0),coalesce(sum(comissao),0),coalesce(sum(desconto),0),coalesce(sum(subtotal),0) into itens,comissoes,descontos,subtotais from comanda_item where comanda_id=cid;
    select coalesce(sum(valor),0) into pagamentos from comanda_pagamento where comanda_id=cid;
    if itens<>c.total or pagamentos<>c.total or comissoes<>c.total_comissao or descontos<>c.desconto or subtotais<>c.subtotal then
        raise exception 'Totais da comanda nao conferem com itens e pagamentos' using errcode='23514';
    end if;
    return null;
end $$;
create constraint trigger ck_comanda_totais after insert or update on comanda deferrable initially deferred for each row execute function barber_conferir_totais_comanda();
create constraint trigger ck_comanda_item_totais after insert or update or delete on comanda_item deferrable initially deferred for each row execute function barber_conferir_totais_comanda();
create constraint trigger ck_comanda_pagamento_totais after insert or update or delete on comanda_pagamento deferrable initially deferred for each row execute function barber_conferir_totais_comanda();
