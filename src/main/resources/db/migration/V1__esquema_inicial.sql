-- Esquema inicial PostgreSQL. Alteracoes posteriores devem usar novas migrations.

create table agendamento (
    data date,
    duracao_servico_minutos integer,
    hora_finalizacao time(0),
    hora_inicio time(0),
    pagamento_recebido boolean,
    preco_total numeric(12,2),
    atualizado_em timestamp(6),
    barbeiro_id bigint not null,
    cliente_id bigint,
    criado_em timestamp(6),
    criado_por_usuario_id bigint,
    finalizado_em timestamp(6),
    id bigint generated by default as identity,
    plano_mensal_cliente_id bigint,
    forma_pagamento varchar(255) check ((forma_pagamento in ('DINHEIRO','PIX','DEBITO','CREDITO','MENSAL'))),
    motivo_cancelamento varchar(255),
    nome_cliente varchar(255),
    nome_servico_plano varchar(255),
    status varchar(255) check ((status in ('AGENDADO','CONCLUIDO','CANCELADO','NAO_COMPARECEU'))),
    telefone_cliente varchar(255),
    primary key (id)
);

create table agendamento_servicos (
    agendamento_id bigint not null,
    servico_id bigint not null,
    primary key (agendamento_id, servico_id)
);

create table agendamento_servicos_plano (
    duracao_minutos integer not null,
    incluso_no_plano boolean not null,
    ordem integer not null check ((ordem>=0)),
    porcentagem_desconto integer not null,
    preco_liquido numeric(12,2) not null,
    preco_original numeric(12,2) not null,
    agendamento_id bigint not null,
    servico_id bigint not null,
    nome varchar(255) not null,
    primary key (ordem, agendamento_id)
);

create table barbeiro (
    ativo boolean not null,
    porcentagem_comissao integer,
    id bigint generated by default as identity,
    usuario_id bigint not null unique,
    imgurl text,
    nome varchar(255) not null,
    telefone varchar(255) not null,
    primary key (id)
);

create table bloqueio_barbeiro (
    data_bloqueio date,
    hora_fim time(0),
    hora_inicio time(0),
    barbeiro_id bigint not null,
    criado_em timestamp(6),
    id bigint generated by default as identity,
    primary key (id)
);

create table caixa (
    saldo_final numeric(12,2) not null,
    saldo_inicial numeric(12,2) not null,
    total_entradas numeric(12,2) not null,
    total_sangrias numeric(12,2) not null,
    aberto_em timestamp(6) not null,
    fechado_em timestamp(6),
    id bigint generated by default as identity,
    status varchar(255) not null check ((status in ('ABERTO','FECHADO'))),
    primary key (id)
);

create table cliente (
    atualizado_em timestamp(6),
    criado_em timestamp(6),
    id bigint generated by default as identity,
    usuario_id bigint unique,
    telefone varchar(20) not null,
    img_url varchar(500),
    nome varchar(255) not null,
    primary key (id)
);

create table comissao_plano (
    data_agendamento date not null,
    pontos integer not null,
    agendamento_id bigint not null unique,
    barbeiro_id bigint not null,
    criado_em timestamp(6) not null,
    id bigint generated by default as identity,
    plano_mensal_cliente_id bigint not null,
    plano_mensal_id bigint not null,
    primary key (id)
);

create table comissao_barbeiro (
    percentual_aplicado numeric(38,2),
    valor_base numeric(38,2),
    valor_comissao numeric(38,2),
    agendamento_id bigint unique,
    barbeiro_id bigint,
    criado_em timestamp(6),
    id bigint generated by default as identity,
    tipo varchar(255) check ((tipo in ('PADRAO_BARBEIRO','PLANO_MENSAL'))),
    primary key (id)
);

create table configuracao_barbearia (
    dias_maximo_antecedentia integer check ((dias_maximo_antecedentia<=30)),
    dias_tolerancia_pagamento_plano integer default 0 check ((dias_tolerancia_pagamento_plano<=30)),
    id bigint not null,
    endereco varchar(255),
    nome varchar(255) not null,
    telefone varchar(255),
    primary key (id)
);

create table horario_funcionamento (
    fechado boolean,
    hora_abertura time(0),
    hora_fechamento time(0),
    intervalo_minimo_entre_agendamentos integer,
    permite_agendamento_plano boolean,
    id bigint generated by default as identity,
    dia_semana varchar(255) not null unique check ((dia_semana in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))),
    primary key (id)
);

create table jornada_barbeiro (
    ativo boolean,
    folga boolean,
    hora_fim time(0),
    hora_inicio time(0),
    intervalo_fim time(0),
    intervalo_inicio time(0),
    barbeiro_id bigint not null,
    id bigint generated by default as identity,
    dia_semana varchar(255) not null check ((dia_semana in ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'))),
    primary key (id),
    constraint uk_jornada_barbeiro_dia unique (barbeiro_id, dia_semana)
);

create table movimento_caixa (
    valor numeric(12,2) not null,
    agendamento_id bigint unique,
    caixa_id bigint not null,
    criado_em timestamp(6) not null,
    id bigint generated by default as identity,
    observacao varchar(255),
    tipo varchar(255) not null check ((tipo in ('ENTRADA','SANGRIA'))),
    primary key (id)
);

create table plano_mensal (
    ativo boolean not null,
    dias_maximo_antecedencia integer,
    valor_mensal numeric(12,2) not null,
    atualizado_em timestamp(6),
    criado_em timestamp(6),
    id bigint generated by default as identity,
    descricao varchar(255) not null,
    nome_plano varchar(255) not null,
    primary key (id)
);

create table plano_mensal_cliente (
    ativo boolean not null,
    dias_maximo_antecedencia integer,
    liberado_ate date,
    pagamento_atrasado boolean,
    proximo_vencimento date,
    valor_mensal numeric(12,2) not null,
    atualizado_em timestamp(6),
    cliente_id bigint not null,
    criado_em timestamp(6),
    id bigint generated by default as identity,
    plano_mensal_id bigint not null,
    usuario_id bigint not null unique,
    primary key (id)
);

create table plano_servicos (
    plano_mensal_id bigint not null,
    servico_id bigint not null,
    primary key (plano_mensal_id, servico_id)
);

create table recebimento_plano (
    data_pagamento date not null,
    valor numeric(12,2) not null,
    vencimento date not null,
    contrato_id bigint not null,
    id bigint generated by default as identity,
    registrado_em timestamp(6) not null,
    referencia varchar(250),
    forma_pagamento varchar(255) not null check ((forma_pagamento in ('DINHEIRO','PIX','DEBITO','CREDITO','MENSAL'))),
    registrado_por varchar(255) not null,
    primary key (id),
    unique (contrato_id, vencimento)
);

create table servico (
    ativo boolean not null,
    duracao_minutos integer not null,
    preco numeric(12,2) not null,
    atualizado_em timestamp(6),
    criado_em timestamp(6),
    id bigint generated by default as identity,
    nome varchar(255) not null,
    primary key (id)
);

create table servicos_planos_desconto (
    porcentagem_desconto integer not null check ((porcentagem_desconto>=0) and (porcentagem_desconto<=100)),
    id bigint generated by default as identity,
    plano_mensal_id bigint not null,
    primary key (id)
);

create table servicos_planos_desconto_servicos (
    desconto_id bigint not null,
    servico_id bigint not null,
    primary key (desconto_id, servico_id)
);

create table usuario (
    ativo boolean,
    id bigint generated by default as identity,
    login varchar(255) not null unique,
    role varchar(255) check ((role in ('ADMIN','BARBEIRO','CLIENTE'))),
    senha varchar(255) not null,
    primary key (id)
);

