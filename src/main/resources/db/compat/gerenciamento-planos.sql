UPDATE plano_mensal_cliente SET proximo_vencimento = CAST(criado_em AS DATE) WHERE proximo_vencimento IS NULL;
CREATE TABLE IF NOT EXISTS recebimento_plano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id BIGINT NOT NULL REFERENCES plano_mensal_cliente(id),
    vencimento DATE NOT NULL,
    data_pagamento DATE NOT NULL,
    valor NUMERIC(12,2) NOT NULL,
    forma_pagamento VARCHAR(255) NOT NULL,
    registrado_em TIMESTAMP NOT NULL,
    registrado_por VARCHAR(255) NOT NULL,
    referencia VARCHAR(250),
    UNIQUE (contrato_id, vencimento)
);
